#!/usr/bin/env python3
"""
Source2Mod: NETWORK_DISCONNECT_* for SourcePawn.

Reads ENetworkDisconnectionReason from s2sdk's common/network_connection.proto
and writes source2mod/consts/disconnect.inc: one #define per reason, under the
proto's (and C++'s) name. For Disconnect(reason), OnClientDisconnect's reason.

    python3 tools/sp_schemagen/sp_disconnect.py <Source2Mod-sdk> <output .inc>
"""
import os
import re
import sys


def generate(sdk, out):
    proto = os.path.join(sdk, "vendor", "s2sdk", "common", "network_connection.proto")
    value_re = re.compile(r"^\s*(NETWORK_DISCONNECT_[A-Z0-9_]+)\s*=\s*(\d+)")
    lines = [
        "// Generated by tools/sp_schemagen/sp_disconnect.py from s2sdk's",
        "// common/network_connection.proto (ENetworkDisconnectionReason). Do not edit.",
        "",
        "#if defined _source2mod_consts_disconnect_included",
        " #endinput",
        "#endif",
        "#define _source2mod_consts_disconnect_included",
        "",
    ]
    count = 0
    in_enum = False
    with open(proto, encoding="utf-8") as f:
        for line in f:
            if line.startswith("enum ENetworkDisconnectionReason"):
                in_enum = True
                continue
            if in_enum and line.startswith("}"):
                break
            m = value_re.match(line) if in_enum else None
            if m:
                lines.append(f"#define {m.group(1)} {m.group(2)}")
                count += 1
    lines.append("")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{count} disconnect reasons -> {out}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    generate(sys.argv[1], sys.argv[2])
