#!/usr/bin/env python3
"""
Source2Mod: net message ids for SourcePawn.

Writes source2mod/netmessage_ids.inc from the game's .proto files: the
message id enums (UM_Shake, CS_UM_..., clc_..., svc_..., net_..., GE_...,
TE_...) as SourcePawn enum constants.

    python3 tools/sp_schemagen/sp_msgids.py <Protobufs/csgo> <output .inc>
"""
import os
import re
import sys

FILES = [
    "networkbasetypes.proto", "netmessages.proto", "usermessages.proto",
    "cstrike15_usermessages.proto", "gameevents.proto", "cs_gameevents.proto", "te.proto",
]
PREFIXES = ("UM_", "CS_UM_", "clc_", "svc_", "net_", "GE_", "TE_", "k_")


def main(proto_dir, out):
    seen = {}
    blocks = []
    enum_re = re.compile(r"^enum\s+(\w+)\s*\{")
    value_re = re.compile(r"^\s*(\w+)\s*=\s*(\d+)\s*;")
    for name in FILES:
        path = os.path.join(proto_dir, name)
        if not os.path.exists(path):
            continue
        current, values = None, []
        with open(path, encoding="utf-8") as f:
            for line in f:
                m = enum_re.match(line.strip())
                if m:
                    current, values = m.group(1), []
                    continue
                if current and line.strip().startswith("}"):
                    kept = [(k, v) for k, v in values if k.startswith(PREFIXES) and k not in seen]
                    if kept:
                        for k, v in kept:
                            seen[k] = v
                        blocks.append((name, current, kept))
                    current = None
                    continue
                if current:
                    m = value_re.match(line)
                    if m:
                        values.append((m.group(1), m.group(2)))

    lines = [
        "// Generated by tools/sp_schemagen/sp_msgids.py from the game's .proto files.",
        "// Do not edit; regenerate when the protobufs change.",
        "",
        "#if defined _source2mod_netmessage_ids_included",
        " #endinput",
        "#endif",
        "#define _source2mod_netmessage_ids_included",
        "",
    ]
    for proto, enum, values in blocks:
        lines.append(f"// {proto}: {enum}")
        lines.append("enum")
        lines.append("{")
        for k, v in values:
            lines.append(f"\t{k} = {v},")
        lines.append("};")
        lines.append("")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(seen)} ids -> {out}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
